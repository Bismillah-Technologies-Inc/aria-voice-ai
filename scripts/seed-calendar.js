/**
 * Seed Google Calendar with test events to create busy slots.
 * This gives getAvailableSlots() realistic data during testing.
 *
 * Usage: node scripts/seed-calendar.js
 * Requires: .env file with GOOGLE_SERVICE_ACCOUNT_EMAIL, GOOGLE_SERVICE_ACCOUNT_PRIVATE_KEY, GOOGLE_CALENDAR_ID
 */

import { google } from 'googleapis';
import { config } from 'dotenv';

config();

const auth = new google.auth.JWT({
  email:  process.env.GOOGLE_SERVICE_ACCOUNT_EMAIL,
  key:    process.env.GOOGLE_SERVICE_ACCOUNT_PRIVATE_KEY.replace(/\\n/g, '\n'),
  scopes: ['https://www.googleapis.com/auth/calendar'],
});

const calendar = google.calendar({ version: 'v3', auth });
const calendarId = process.env.GOOGLE_CALENDAR_ID || 'primary';

async function seedEvents() {
  const now = new Date();
  const events = [];

  // Create busy slots for the next 5 business days
  for (let dayOffset = 0; dayOffset < 7 && events.length < 8; dayOffset++) {
    const day = new Date(now);
    day.setDate(day.getDate() + dayOffset);

    // Skip weekends
    if (day.getDay() === 0 || day.getDay() === 6) continue;

    // Create 2 busy slots per day at semi-random hours
    const hours = dayOffset % 2 === 0 ? [10, 14] : [11, 15];

    for (const hour of hours) {
      const start = new Date(day);
      start.setHours(hour, 0, 0, 0);
      const end = new Date(start);
      end.setMinutes(30);

      events.push({
        summary: `[Test] Busy slot - seeded`,
        description: 'Auto-generated by seed-calendar.js for testing availability.',
        start: { dateTime: start.toISOString(), timeZone: 'America/Chicago' },
        end:   { dateTime: end.toISOString(),   timeZone: 'America/Chicago' },
      });
    }
  }

  console.log(`Creating ${events.length} test events...`);

  for (const event of events) {
    const res = await calendar.events.insert({ calendarId, requestBody: event });
    console.log(`  Created: ${event.summary} — ${event.start.dateTime} (${res.data.id})`);
  }

  console.log('Done. Run getAvailableSlots() to see remaining open slots.');
}

seedEvents().catch((err) => {
  console.error('Error seeding calendar:', err.message);
  process.exit(1);
});
